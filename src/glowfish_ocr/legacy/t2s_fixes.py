# 词级修正（多字词优先于字表；目前留空位，归因样本积累后填充，同样须实测）
_WORD_FIXES = {}

_TRANS = str.maketrans(_CHAR_FIXES)


def apply(text):
    """对 t2s 之后的简体文本做修正；空值原样返回。"""
    if not text:
        return text
    for w, r in _WORD_FIXES.items():
        if w in text:
            text = text.replace(w, r)
    return text.translate(_TRANS)
